import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const englishPath = path.join(root, "data", "dictionaries", "english-words.txt");
const categoriesPath = path.join(root, "data", "categories");
const outputPath = path.join(root, "src", "dictionary-data.js");

const englishWords = fs.readFileSync(englishPath, "utf8").split(/\r?\n/).filter(Boolean);
const categoryFiles = fs.readdirSync(categoriesPath).filter((file) => file.endsWith(".json")).sort();
const categories = Object.fromEntries(categoryFiles.map((file) => {
  const category = JSON.parse(fs.readFileSync(path.join(categoriesPath, file), "utf8"));
  return [category.id, category.accepted_headwords];
}));

const output = [
  "// Generated by scripts/build-dictionary-data.js. Edit data/ files, then rebuild.",
  `export const ENGLISH_WORDS = new Set(${JSON.stringify(englishWords)});`,
  `export const CATEGORY_LEXICONS = ${JSON.stringify(Object.fromEntries(Object.entries(categories).map(([id, words]) => [id, words])))};`,
  ""
].join("\n");

fs.writeFileSync(outputPath, output);
console.log(`Generated ${englishWords.length} English words and ${Object.keys(categories).length} category lexicons: ${outputPath}`);
